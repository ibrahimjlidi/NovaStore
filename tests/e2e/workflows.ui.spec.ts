import { expect, test } from '@playwright/test'
import { readE2eContext } from './context.js'
import { resetStore } from './reset-store.js'

test.beforeEach(async () => {
  await resetStore(await readE2eContext())
})

test('admin signs in, completes inventory workflows, exports reports, and manages a viewer', async ({ page }) => {
  test.setTimeout(120_000)
  await page.addInitScript(() => {
    window.print = () => window.sessionStorage.setItem('e2e-print-called', 'true')
  })
  const data = await readE2eContext()
  await page.goto('/')
  await page.getByRole('button', { name: 'Français' }).click()
  await expect(page.getByRole('heading', { name: 'Connexion' })).toBeVisible()
  await page.getByLabel('E-mail').fill(data.adminEmail)
  await page.getByLabel('Mot de passe').fill(data.adminPassword)
  await page.getByRole('button', { name: 'Connexion' }).click()
  await expect(page.getByRole('heading', { name: 'Vue d’ensemble' })).toBeVisible()

  await page.getByRole('button', { name: 'Theme' }).click()
  await expect(page.locator('.app-shell')).toHaveClass(/theme-dark/)

  await page.getByRole('navigation').getByRole('button', { name: 'Produits' }).click()
  await expect(page.getByRole('heading', { name: 'Produits' })).toBeVisible()
  const basePhoto = page.locator('img[alt="Produit de test"]')
  await expect(basePhoto).toBeVisible()
  await expect.poll(() => basePhoto.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  await page.getByPlaceholder('Rechercher un produit ou SKU…').fill('E2E-BASE-001')
  await expect(page.getByRole('row').filter({ hasText: 'E2E-BASE-001' })).toBeVisible()
  await page.getByPlaceholder('Rechercher un produit ou SKU…').fill('')
  await page.getByLabel('Catégorie').selectOption('jeans')
  await expect(page.getByRole('row').filter({ hasText: 'E2E-BASE-001' })).toHaveCount(0)
  await page.getByLabel('Catégorie').selectOption('all')
  await page.getByLabel('Taille').selectOption('S')
  await expect(page.getByRole('row').filter({ hasText: 'E2E-BASE-001' })).toHaveCount(0)
  await page.getByLabel('Taille').selectOption('all')
  await page.getByLabel('Couleur').selectOption('noir')
  await expect(page.getByRole('row').filter({ hasText: 'E2E-BASE-001' })).toBeVisible()
  await page.getByLabel('Couleur').selectOption('all')
  await page.getByLabel('Stock faible uniquement').check()
  await expect(page.getByRole('row').filter({ hasText: 'E2E-BASE-001' })).toHaveCount(0)
  await page.getByLabel('Stock faible uniquement').uncheck()

  const csvSku = `E2E-UI-${Date.now()}`
  const csv = [
    'sku,name_ar,name_fr,category,price_tnd,low_stock_threshold,size,color_key,color_ar,color_fr,color_hex,opening_quantity',
    `${csvSku},منتج واجهة,Produit interface,dress,42,2,M,vert,أخضر,Vert,#667C62,3`,
  ].join('\n')
  await page.getByRole('button', { name: 'Importer CSV' }).click()
  const importDialog = page.getByRole('dialog')
  await importDialog.locator('input[type="file"]').setInputFiles({
    name: 'ui-products.csv',
    mimeType: 'text/csv',
    buffer: Buffer.from(csv),
  })
  await expect(importDialog.getByText('1 produits')).toBeVisible()
  await page.once('dialog', (dialog) => dialog.accept())
  await importDialog.getByRole('button', { name: 'Confirmer l’import' }).click()
  await expect(importDialog).toBeHidden()
  await expect(page.getByRole('row').filter({ hasText: csvSku })).toBeVisible()

  const productSku = `E2E-UI-P-${Date.now()}`
  await page.getByRole('button', { name: 'Ajouter un produit' }).click()
  const productDialog = page.getByRole('dialog', { name: 'Ajouter un produit' })
  await productDialog.getByLabel('SKU').fill(productSku)
  await productDialog.getByLabel('Choisir une catégorie').selectOption('jeans')
  await productDialog.getByLabel('Nom en arabe').fill('منتج واجهة')
  await productDialog.getByLabel('Nom en français').fill('Produit interface')
  await productDialog.getByLabel('Prix').fill('65.500')
  await productDialog.getByLabel('Seuil d’alerte').fill('4')
  await productDialog.getByLabel('Color key').fill('bleu-ui')
  await productDialog.getByLabel('Nom couleur arabe').fill('أزرق')
  await productDialog.getByLabel('Nom couleur français').fill('Bleu')
  await productDialog.getByRole('button', { name: 'Enregistrer' }).click()
  const createdRow = page.getByRole('row').filter({ hasText: productSku })
  await expect(createdRow).toBeVisible()

  await createdRow.getByRole('button', { name: 'Modifier' }).click()
  const editDialog = page.getByRole('dialog', { name: 'Modifier' })
  await editDialog.getByLabel('Nom en français').fill('Produit modifié')
  await editDialog.getByRole('button', { name: 'Enregistrer' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Produit modifié' })).toBeVisible()

  await page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('row').filter({ hasText: productSku }).getByRole('button', { name: 'Archiver' }).click()
  await expect(page.getByRole('row').filter({ hasText: productSku })).toHaveCount(0)

  await page.getByRole('navigation').getByRole('button', { name: 'Mouvements' }).click()
  await page.getByRole('button', { name: 'Nouveau mouvement' }).click()
  const movementDialog = page.getByRole('dialog', { name: 'Nouveau mouvement' })
  await movementDialog.getByLabel('Taille et couleur').selectOption(data.variantId)
  await movementDialog.getByLabel('Type').selectOption('IN')
  await movementDialog.getByLabel('Quantité').fill('2')
  await movementDialog.getByLabel('Note facultative').fill('e2e-ui-movement')
  await movementDialog.getByRole('button', { name: 'Créer' }).click()
  await expect(page.getByText('e2e-ui-movement')).toBeVisible()

  await page.getByRole('navigation').getByRole('button', { name: 'Fournisseurs et commandes' }).click()
  await page.getByRole('button', { name: 'Ajouter un fournisseur' }).click()
  const supplierName = `E2E UI supplier ${Date.now()}`
  const supplierDialog = page.getByRole('dialog', { name: 'Ajouter un fournisseur' })
  await supplierDialog.getByLabel('Fournisseur').fill(supplierName)
  await supplierDialog.getByLabel('Téléphone').fill('+216 71 000 000')
  await supplierDialog.getByLabel('Ville').fill('Tunis')
  await supplierDialog.getByRole('button', { name: 'Enregistrer' }).click()
  await expect(page.getByRole('row').filter({ hasText: supplierName })).toBeVisible()

  await page.getByRole('button', { name: /Commandes/ }).click()
  await page.getByRole('button', { name: 'Nouvelle commande' }).click()
  const orderDialog = page.getByRole('dialog', { name: 'Créer une commande' })
  await orderDialog.getByLabel('Fournisseur').selectOption({ label: supplierName })
  await orderDialog.locator('.order-draft-row select').first().selectOption(data.variantId)
  await orderDialog.getByRole('spinbutton', { name: 'Quantité' }).fill('2')
  await orderDialog.getByRole('spinbutton', { name: 'Coût unitaire' }).fill('10')
  await orderDialog.getByRole('button', { name: 'Créer' }).click()
  const orderRow = page.getByRole('row').filter({ hasText: supplierName })
  await expect(orderRow).toBeVisible()
  await orderRow.getByRole('button', { name: 'Envoyer' }).click()
  await expect(orderRow.getByRole('button', { name: 'Confirmer la réception' })).toBeVisible()
  await page.once('dialog', (dialog) => dialog.accept())
  await orderRow.getByRole('button', { name: 'Confirmer la réception' }).click()
  await expect(orderRow).toContainText('Reçue')

  await page.getByRole('navigation').getByRole('button', { name: 'Mouvements' }).click()
  await page.getByRole('button', { name: 'Nouveau mouvement' }).click()
  const outgoingDialog = page.getByRole('dialog', { name: 'Nouveau mouvement' })
  await outgoingDialog.getByLabel('Taille et couleur').selectOption(data.variantId)
  await outgoingDialog.getByLabel('Type').selectOption('OUT')
  await outgoingDialog.getByLabel('Quantité').fill('15')
  await outgoingDialog.getByRole('button', { name: 'Créer' }).click()
  await page.getByRole('navigation').getByRole('button', { name: 'Alertes' }).click()
  const alertRow = page.getByRole('row').filter({ hasText: 'E2E-BASE-001' })
  await expect(alertRow).toBeVisible()
  await alertRow.getByRole('button', { name: 'Commander ce produit' }).click()
  const alertOrderDialog = page.getByRole('dialog', { name: 'Créer une commande' })
  await alertOrderDialog.getByRole('button', { name: 'Créer' }).click()
  await expect(alertOrderDialog).toBeHidden()
  await page.getByRole('navigation').getByRole('button', { name: 'Fournisseurs et commandes' }).click()
  await page.getByRole('button', { name: /Commandes/ }).click()
  await expect(page.getByRole('row').filter({ hasText: supplierName })).toBeVisible()

  await page.getByRole('navigation').getByRole('button', { name: 'Rapports' }).click()
  await expect(page.getByRole('heading', { name: 'Valorisation du stock' })).toBeVisible()
  await page.getByRole('combobox').first().selectOption('7')
  await page.getByRole('button', { name: 'Imprimer / PDF' }).click()
  await expect.poll(() => page.evaluate(() => window.sessionStorage.getItem('e2e-print-called'))).toBe('true')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exporter CSV' }).first().click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('novastore-inventory.csv')
  await expect(page.getByRole('row').filter({ hasText: 'E2E-BASE-001' })).toBeVisible()

  await page.getByRole('navigation').getByRole('button', { name: 'Utilisateurs et rôles' }).click()
  await expect(page.getByRole('heading', { name: 'Inviter un membre' })).toBeVisible()
  const storekeeperRow = page.getByRole('row').filter({ hasText: data.storekeeperEmail })
  const storekeeperRole = storekeeperRow.getByRole('combobox')
  await storekeeperRole.selectOption('viewer')
  await expect(storekeeperRole).toHaveValue('viewer')
  await storekeeperRole.selectOption('storekeeper')
  await expect(storekeeperRole).toHaveValue('storekeeper')
  await page.once('dialog', (dialog) => dialog.accept())
  await storekeeperRow.getByRole('button', { name: 'Désactiver' }).click()
  await expect(storekeeperRow).toContainText('Désactivé')
  await storekeeperRow.getByRole('button', { name: 'Réactiver' }).click()
  await expect(storekeeperRow).toContainText('Actif')
  const inviteEmail = `ui-invite-${Date.now()}@e2e.invalid`
  await page.getByLabel('E-mail du membre').fill(inviteEmail)
  await page.getByLabel('Rôle').selectOption('viewer')
  await page.getByRole('button', { name: 'Envoyer l’invitation' }).click()
  const invitationLink = page.getByRole('link', { name: /\/invite\?token=/ })
  await expect(invitationLink).toBeVisible()
  await page.getByRole('row').filter({ hasText: data.viewerEmail })
    .getByRole('button', { name: 'Créer un lien de réinitialisation' }).click()
  const resetLink = page.getByRole('link', { name: /\/reset-password\?token=/ })
  await expect(resetLink).toBeVisible()

  const invitationUrl = await invitationLink.getAttribute('href')
  const resetUrl = await resetLink.getAttribute('href')
  if (!invitationUrl) throw new Error('The invitation link did not expose a URL.')
  if (!resetUrl) throw new Error('The password-reset link did not expose a URL.')
  await page.getByRole('button', { name: 'Déconnexion' }).last().click()
  await expect(page.getByRole('heading', { name: 'Connexion' })).toBeVisible()
  await page.goto(invitationUrl)
  await page.getByRole('button', { name: 'Français' }).click()
  await expect(page.getByRole('heading', { name: 'Accepter l’invitation' })).toBeVisible()
  await page.getByLabel('E-mail invité').fill(inviteEmail)
  await page.getByLabel('Nouveau mot de passe').fill('ui-accepted-account-password')
  await page.getByLabel('Confirmer le mot de passe').fill('ui-accepted-account-password')
  await page.getByRole('button', { name: 'Accepter l’invitation' }).click()
  await expect(page.getByText(/Invitation acceptée/)).toBeVisible()
  await page.getByLabel('E-mail').fill(inviteEmail)
  await page.getByLabel('Mot de passe').fill('ui-accepted-account-password')
  await page.getByRole('button', { name: 'Connexion' }).click()
  await expect(page.getByRole('heading', { name: 'Vue d’ensemble' })).toBeVisible()
  await expect(page.getByRole('navigation').getByRole('button', { name: 'Rapports' })).toBeVisible()
  await expect(page.getByRole('navigation').getByRole('button', { name: 'Utilisateurs et rôles' })).toHaveCount(0)
  await page.getByRole('navigation').getByRole('button', { name: 'Alertes' }).click()
  await expect(page.getByRole('heading', { name: 'Alertes', level: 1 })).toBeVisible()

  await page.getByRole('button', { name: 'Déconnexion' }).last().click()
  await expect(page.getByRole('heading', { name: 'Connexion' })).toBeVisible()
  await page.goto(resetUrl)
  await page.getByRole('button', { name: 'Français' }).click()
  await expect(page.getByRole('heading', { name: 'Réinitialiser le mot de passe' })).toBeVisible()
  await page.getByLabel('Nouveau mot de passe').fill('ui-reset-account-password')
  await page.getByLabel('Confirmer le mot de passe').fill('ui-reset-account-password')
  await page.getByRole('button', { name: 'Réinitialiser le mot de passe' }).click()
  await expect(page.getByText(/Mot de passe modifié/)).toBeVisible()

  await page.getByRole('button', { name: 'Mot de passe oublié ?' }).click()
  await page.getByLabel('E-mail').fill(data.viewerEmail)
  await page.getByRole('button', { name: 'Créer un lien de réinitialisation' }).click()
  await expect(page.getByText('L’envoi d’e-mails n’est pas activé. Demandez un lien à l’administrateur du magasin.')).toBeVisible()
  await page.getByRole('button', { name: 'Retour à la connexion' }).click()
  await page.getByLabel('E-mail').fill(data.viewerEmail)
  await page.getByLabel('Mot de passe').fill('ui-reset-account-password')
  await page.getByRole('button', { name: 'Connexion' }).click()
  await expect(page.getByRole('heading', { name: 'Vue d’ensemble' })).toBeVisible()
  const navigation = page.getByRole('navigation')
  await expect(navigation.getByRole('button', { name: 'Rapports' })).toBeVisible()
  await expect(navigation.getByRole('button', { name: 'Utilisateurs et rôles' })).toHaveCount(0)
  await expect(navigation.getByRole('button', { name: 'Mouvements' })).toHaveCount(0)
  await expect(navigation.getByRole('button', { name: 'Fournisseurs et commandes' })).toHaveCount(0)
  await navigation.getByRole('button', { name: 'Produits' }).click()
  await expect(page.getByRole('button', { name: 'Ajouter un produit' })).toHaveCount(0)
})
